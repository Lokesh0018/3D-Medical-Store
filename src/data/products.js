export const formatPrice = (n) =>
  new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', maximumFractionDigits: 0 }).format(n)

export const discountPercent = (p) => (p.mrp > p.price ? Math.round(((p.mrp - p.price) / p.mrp) * 100) : 0)

export const productPath = (p) => `/products/${p.id}`

export const categoryName = (id) => CATEGORIES.find((c) => c.id === id)?.name ?? id

/** WhatsApp enquiry for an out-of-stock item. */
